/// 单字节 XOR 混淆解码：源码与注释里不存放任何明文敏感串，
/// 只存加密字节数组，运行时解密进内存。
enum Obfuscated {
    static func decode(_ bytes: [UInt8], key: UInt8) -> String {
        let decoded = bytes.map { $0 ^ key }
        return String(bytes: decoded, encoding: .utf8) ?? ""
    }
}

